//! Compile-time code generation for `plsfix`:
//!
//! - `lookup_upper_alias` — `phf::Map`-backed perfect-hash for ftfy's
//!   ALL-CAPS HTML entity aliases (`&EACUTE;` → `É`), derived from
//!   `htmlize::ENTITIES`. Replaces a ~500 µs lazy_static FxHashMap init.
//! - `UTF8_CONTINUATION_STRICT_SET` — `phf::Set<char>` reconstructing the
//!   char class from the lookbehind dropped from `UTF8_DETECTOR_RE`. The
//!   name list mirrors `test_utf8_clues_match_ftfy` in `chardata.rs`.

use std::collections::BTreeSet;
use std::env;
use std::fs::File;
use std::io::{BufWriter, Write};
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    write_html_entity_overlay(&out_dir.join("html_entities.rs"));
    write_strict_continuation_set(&out_dir.join("utf8.rs"));
}

fn write_html_entity_overlay(out_path: &std::path::Path) {
    let mut out = BufWriter::new(File::create(out_path).unwrap());

    let mut entries: Vec<(String, String)> = Vec::new();
    for (name_bytes, val_bytes) in htmlize::ENTITIES.entries() {
        let name = match std::str::from_utf8(name_bytes) {
            Ok(s) => s,
            Err(_) => continue,
        };
        if !name.ends_with(';') {
            continue;
        }
        let bare = &name[1..name.len() - 1];
        if !bare.chars().all(|c| !c.is_alphabetic() || c.is_lowercase()) {
            continue;
        }
        let upper_key = format!("&{};", bare.to_uppercase());
        if htmlize::ENTITIES.contains_key(upper_key.as_bytes()) {
            continue;
        }
        let val = match std::str::from_utf8(val_bytes) {
            Ok(s) => s,
            Err(_) => continue,
        };
        entries.push((upper_key, val.to_uppercase()));
    }

    writeln!(
        out,
        "/// Look up an ftfy ALL-CAPS HTML entity alias. Returns the decoded\n\
         /// value or `None`. Generated by `build.rs` from `htmlize::ENTITIES`."
    )
    .unwrap();
    let mut builder = phf_codegen::Map::<&str>::new();
    let escaped_vals: Vec<String> = entries
        .iter()
        .map(|(_, v)| rust_string_literal(v))
        .collect();
    for ((key, _), val_lit) in entries.iter().zip(escaped_vals.iter()) {
        builder.entry(key.as_str(), val_lit);
    }
    writeln!(
        out,
        "static UPPER_ALIASES: phf::Map<&'static str, &'static str> = {};",
        builder.build()
    )
    .unwrap();
    writeln!(
        out,
        "pub fn lookup_upper_alias(key: &str) -> Option<&'static str> {{ UPPER_ALIASES.get(key).copied() }}"
    )
    .unwrap();
}

/// Format a string as a Rust `"…"` literal with `\u{…}` escapes for any
/// non-ASCII codepoint, so the generated source is plain ASCII.
fn rust_string_literal(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            c if (c as u32) < 0x20 || c == '\u{7f}' => {
                out.push_str(&format!("\\u{{{:x}}}", c as u32));
            }
            c if (c as u32) < 0x80 => out.push(c),
            c => out.push_str(&format!("\\u{{{:x}}}", c as u32)),
        }
    }
    out.push('"');
    out
}

