fn write_strict_continuation_set(out_path: &std::path::Path) {
    let mut out = BufWriter::new(File::create(out_path).unwrap());

    // BTreeSet for stable codegen output and to dedupe in case a named char
    // overlaps with the byte range (currently none do).
    let mut chars: BTreeSet<char> = ('\u{80}'..='\u{bf}').collect();
    for name in STRICT_NAMES {
        let ch = unicode_names2::character(name)
            .unwrap_or_else(|| panic!("unknown Unicode name {name:?}"));
        chars.insert(ch);
    }

    let mut builder = phf_codegen::Set::<char>::new();
    for c in &chars {
        builder.entry(*c);
    }

    writeln!(
        out,
        "/// Char class that the dropped `(?<![strict])` lookbehind of `UTF8_DETECTOR_RE`\n\
         /// excluded. Reconstructed in `decode_inconsistent_utf8` to filter rejected\n\
         /// matches. Source of truth: `build.rs::STRICT_NAMES`.\n\
         pub static UTF8_CONTINUATION_STRICT_SET: phf::Set<char> = {};",
        builder.build()
    )
    .unwrap();
}
